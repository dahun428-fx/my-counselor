# 위기 감지 키워드
CRISIS_KEYWORDS = [
    "죽고 싶",
    "죽을래",
    "자살",
    "살고 싶지 않",
    "사라지고 싶",
    "없어지고 싶",
    "자해",
    "목숨",
    "유서",
    "삶을 끝",
    "더 이상 못",
    "세상에서 사라",
    "죽어버리",
    "생을 마감",
    "극단적",
]


def detect_crisis(message: str) -> bool:
    """메시지에서 위기 키워드를 감지합니다."""
    return any(keyword in message for keyword in CRISIS_KEYWORDS)
